BEGIN;

CREATE TABLE IF NOT EXISTS hospitals (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name VARCHAR(255) NOT NULL,
  code VARCHAR(80) UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
INSERT INTO hospitals(name, code) VALUES ('Default Hospital', 'default') ON CONFLICT (code) DO NOTHING;
CREATE OR REPLACE FUNCTION hms_default_hospital_id() RETURNS UUID LANGUAGE SQL STABLE AS $$
  SELECT id FROM hospitals WHERE code='default' LIMIT 1
$$;
CREATE OR REPLACE FUNCTION hms_current_hospital_id() RETURNS UUID LANGUAGE SQL STABLE AS $$
  SELECT COALESCE(NULLIF(current_setting('app.hospital_id', true), '')::uuid, hms_default_hospital_id())
$$;

ALTER TABLE users ADD COLUMN IF NOT EXISTS last_failed_login TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS active_session_id UUID;

CREATE OR REPLACE FUNCTION prevent_audit_log_mutation()
RETURNS TRIGGER AS $$ BEGIN
  RAISE EXCEPTION 'audit_logs is strictly append-only';
END; $$ LANGUAGE plpgsql;
DO $$ BEGIN
  IF to_regclass('audit_logs') IS NOT NULL THEN
    DROP TRIGGER IF EXISTS trg_audit_logs_no_mutation ON audit_logs;
    CREATE TRIGGER trg_audit_logs_no_mutation BEFORE UPDATE OR DELETE ON audit_logs
      FOR EACH ROW EXECUTE FUNCTION prevent_audit_log_mutation();
  END IF;
END $$;

-- Deliberately stores only UIDAI audit metadata; no column exists for Aadhaar,
-- PID block, session key, or HMAC material.
CREATE TABLE IF NOT EXISTS aadhaar_kyc_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hospital_id UUID REFERENCES hospitals(id),
  user_id UUID REFERENCES users(id) ON DELETE SET NULL,
  tid VARCHAR(128),
  ver VARCHAR(32),
  txn VARCHAR(128),
  ts TIMESTAMPTZ,
  modality VARCHAR(40),
  rd VARCHAR(80),
  rc VARCHAR(80),
  uid_token VARCHAR(512),
  status VARCHAR(32) NOT NULL,
  error_code VARCHAR(80),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT aadhaar_audit_status_check CHECK (status IN ('SUCCESS','FAILURE','PENDING'))
);
CREATE INDEX IF NOT EXISTS idx_aadhaar_kyc_audit_created_at
  ON aadhaar_kyc_audit_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_aadhaar_kyc_audit_hospital_created
  ON aadhaar_kyc_audit_logs(hospital_id, created_at);
ALTER TABLE aadhaar_kyc_audit_logs ALTER COLUMN hospital_id SET DEFAULT hms_current_hospital_id();
ALTER TABLE aadhaar_kyc_audit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE aadhaar_kyc_audit_logs FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON aadhaar_kyc_audit_logs;
CREATE POLICY tenant_isolation ON aadhaar_kyc_audit_logs
  USING (hospital_id = hms_current_hospital_id())
  WITH CHECK (hospital_id = hms_current_hospital_id());

CREATE OR REPLACE FUNCTION prune_aadhaar_kyc_audit_logs()
RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE removed BIGINT;
BEGIN
  DELETE FROM aadhaar_kyc_audit_logs WHERE created_at < now() - interval '2 years';
  GET DIAGNOSTICS removed = ROW_COUNT;
  RETURN removed;
END; $$;

COMMIT;
